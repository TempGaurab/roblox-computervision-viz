"""Quantize and generate ModelData.luau, Dev/Fixtures.luau, and tests/golden/*: python -m training.export."""

import base64
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch

from training import config
from training.preprocess import decode_strokes, encode_strokes, preprocess
from training.train import accuracy, build_model, load_mnist, split_train_validation


@dataclass
class Layer:
    """One dense layer. `quantized` and `weights` are indexed [input, output]."""

    quantized: np.ndarray
    scales: np.ndarray
    biases: np.ndarray
    weights: np.ndarray
    activation: str
    act_scale: np.ndarray


@dataclass
class StrokeFixture:
    digit: int
    name: str
    encoded: str


def quantize_layers(state_dict: dict[str, torch.Tensor]) -> list[Layer]:
    """Symmetric int8 per output neuron: scale = max|w| / 127, round, clamp to +-127."""
    layers: list[Layer] = []
    linear_keys = sorted(
        {key.rsplit(".", 1)[0] for key in state_dict if key.endswith(".weight")}, key=lambda name: int(name)
    )
    for position, key in enumerate(linear_keys):
        # PyTorch stores [output, input]; everything downstream is input-major.
        raw = state_dict[f"{key}.weight"].numpy().astype(np.float64).T
        max_abs = np.abs(raw).max(axis=0)
        scales = np.where(max_abs > 0.0, max_abs / config.INT8_MAX, 1.0)
        quantized = np.clip(np.rint(raw / scales), -config.INT8_MAX, config.INT8_MAX).astype(np.int8)
        layers.append(
            Layer(
                quantized=quantized,
                scales=scales,
                biases=state_dict[f"{key}.bias"].numpy().astype(np.float64),
                weights=quantized.astype(np.float64) * scales,
                activation="softmax" if position == len(linear_keys) - 1 else "relu",
                act_scale=np.ones(quantized.shape[1], dtype=np.float64),
            )
        )
    return layers


def forward_all(layers: list[Layer], inputs: np.ndarray) -> list[np.ndarray]:
    """Float64 forward pass over dequantized weights. Returns each layer's activations; the last are logits."""
    activations: list[np.ndarray] = []
    current = inputs
    for layer in layers:
        current = current @ layer.weights + layer.biases
        if layer.activation == "relu":
            current = np.maximum(current, 0.0)
        activations.append(current)
    return activations


def logits_of(layers: list[Layer], inputs: np.ndarray) -> np.ndarray:
    return forward_all(layers, inputs)[-1]


def accuracy_of(layers: list[Layer], inputs: np.ndarray, labels: np.ndarray) -> float:
    return 100.0 * float((logits_of(layers, inputs).argmax(axis=1) == labels).mean())


def fill_act_scales(layers: list[Layer], validation_inputs: np.ndarray) -> None:
    """Record p99 activation on validation data for the visuals. A neuron that never fires gets 1."""
    for layer, activations in zip(layers, forward_all(layers, validation_inputs)):
        percentile = np.percentile(activations, config.ACT_SCALE_PERCENTILE, axis=0)
        layer.act_scale = np.where(percentile > 0.0, percentile, 1.0)


def model_version(layers: list[Layer]) -> str:
    digest = hashlib.sha256()
    for layer in layers:
        digest.update(layer.quantized.tobytes())
        digest.update(layer.scales.tobytes())
        digest.update(layer.biases.tobytes())
    return digest.hexdigest()[:8]


def _luau_numbers(values: np.ndarray) -> str:
    return "{ " + ", ".join(repr(float(value)) for value in values) + " }"


def _write_generated(path: Path, text: str) -> None:
    if len(text) > config.MAX_GENERATED_CHARS:
        raise SystemExit(f"{path} is {len(text)} characters, over the {config.MAX_GENERATED_CHARS} limit")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {path.relative_to(config.REPO_ROOT)} ({len(text)} characters)")


def write_model_data(layers: list[Layer], version: str, metrics: dict[str, float]) -> None:
    lines = [
        "--!strict",
        "-- AUTO-GENERATED by training/export.py. DO NOT EDIT.",
        "return {",
        "\tformatVersion = 1,",
        f'\tmodelVersion = "{version}",',
        "\tpreprocess = {",
        f"\t\tgrid = {config.GRID},",
        f"\t\tbox = {config.BOX},",
        f"\t\tbrushInner = {config.BRUSH_INNER!r},",
        f"\t\tbrushOuter = {config.BRUSH_OUTER!r},",
        f"\t\tminExtent = {config.MIN_EXTENT!r},",
        "\t},",
        "\tlayers = {",
    ]
    for layer in layers:
        encoded = base64.b64encode(layer.quantized.tobytes(order="C")).decode("ascii")
        lines += [
            "\t\t{",
            f"\t\t\tinSize = {layer.quantized.shape[0]},",
            f"\t\t\toutSize = {layer.quantized.shape[1]},",
            f'\t\t\tactivation = "{layer.activation}",',
            f'\t\t\tweights = "{encoded}",',
            f"\t\t\tscales = {_luau_numbers(layer.scales)},",
            f"\t\t\tbiases = {_luau_numbers(layer.biases)},",
            f"\t\t\tactScale = {_luau_numbers(layer.act_scale)},",
            "\t\t},",
        ]
    lines += [
        "\t},",
        "\t-- strokeFixtureAcc is -1 when no recorded fixtures exist yet.",
        "\tmetrics = {",
        f"\t\tfloatTestAcc = {metrics['float']!r},",
        f"\t\tint8TestAcc = {metrics['int8']!r},",
        f"\t\tstrokeFixtureAcc = {metrics['fixture']!r},",
        "\t},",
        "}",
        "",
    ]
    _write_generated(config.MODEL_DATA_PATH, "\n".join(lines))


def load_stroke_fixtures() -> list[StrokeFixture]:
    fixtures: list[StrokeFixture] = []
    for path in sorted(config.STROKE_FIXTURE_DIR.glob("*.b64")):
        fixtures.append(
            StrokeFixture(digit=int(path.stem.split("_")[0]), name=path.stem, encoded=path.read_text().strip())
        )
    return fixtures


def fixture_accuracy(layers: list[Layer], fixtures: list[StrokeFixture]) -> float:
    """Percent correct on recorded drawings, or -1 when there are none."""
    if not fixtures:
        return -1.0
    correct = 0
    for fixture in fixtures:
        image = preprocess(*decode_strokes(base64.b64decode(fixture.encoded)))
        if image is not None and int(logits_of(layers, image[np.newaxis])[0].argmax()) == fixture.digit:
            correct += 1
    return 100.0 * correct / len(fixtures)


def write_dev_fixtures(fixtures: list[StrokeFixture]) -> None:
    lines = ["--!strict", "-- AUTO-GENERATED by training/export.py. DO NOT EDIT.", "return {"]
    per_digit: dict[int, int] = {}
    for fixture in fixtures:
        taken = per_digit.get(fixture.digit, 0)
        if taken < config.DEV_FIXTURES_PER_DIGIT:
            per_digit[fixture.digit] = taken + 1
            lines.append(f'\t{{ digit = {fixture.digit}, strokes = "{fixture.encoded}" }},')
    lines += ["}", ""]
    _write_generated(config.DEV_FIXTURES_PATH, "\n".join(lines))


def _b64_float64(values: np.ndarray) -> str:
    return base64.b64encode(values.astype("<f8").tobytes()).decode("ascii")


def _random_polyline(rng: np.random.Generator) -> bytes:
    """A seeded scribble covering dots, single segments, and several strokes, above the minimum extent."""
    while True:
        xs: list[int] = []
        ys: list[int] = []
        ends: list[int] = []
        for _ in range(int(rng.integers(1, 6))):
            x, y = rng.integers(0, 65536, size=2)
            for _ in range(int(rng.integers(1, 25))):
                xs.append(int(x))
                ys.append(int(y))
                x = int(np.clip(x + rng.integers(-9000, 9001), 0, 65535))
                y = int(np.clip(y + rng.integers(-9000, 9001), 0, 65535))
            ends.append(len(xs))
        if preprocess(xs, ys, ends) is not None:
            return encode_strokes(xs, ys, ends)


def _write_golden(name: str, payload: dict[str, object]) -> None:
    config.GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
    path = config.GOLDEN_DIR / name
    path.write_text(json.dumps(payload, indent=0, sort_keys=True) + "\n")
    print(f"wrote {path.relative_to(config.REPO_ROOT)}")


def write_goldens(
    layers: list[Layer], version: str, test_inputs: np.ndarray, test_labels: np.ndarray, fixtures: list[StrokeFixture]
) -> None:
    mnist_cases = []
    for index in range(config.GOLDEN_MNIST_CASES):
        logits = logits_of(layers, test_inputs[index][np.newaxis])[0]
        mnist_cases.append(
            {
                "label": int(test_labels[index]),
                "input": _b64_float64(test_inputs[index]),
                "logits": _b64_float64(logits),
                "top": int(logits.argmax()),
            }
        )
    _write_golden("mnist.json", {"modelVersion": version, "cases": mnist_cases})

    rng = np.random.default_rng(config.GOLDEN_SEED)
    stroke_sources = [
        (f"polyline_{index}", _random_polyline(rng)) for index in range(config.GOLDEN_POLYLINE_CASES)
    ] + [(fixture.name, base64.b64decode(fixture.encoded)) for fixture in fixtures]

    stroke_cases = []
    for name, payload in stroke_sources:
        image = preprocess(*decode_strokes(payload))
        if image is None:
            raise SystemExit(f"stroke case {name} preprocesses to nothing")
        logits = logits_of(layers, image[np.newaxis])[0]
        stroke_cases.append(
            {
                "name": name,
                "strokes": base64.b64encode(payload).decode("ascii"),
                "expected": _b64_float64(image),
                "logits": _b64_float64(logits),
                "top": int(logits.argmax()),
            }
        )
    _write_golden("strokes.json", {"modelVersion": version, "cases": stroke_cases})


def main() -> None:
    checkpoint = torch.load(config.CHECKPOINT_PATH, weights_only=True)
    state_dict: dict[str, torch.Tensor] = checkpoint["state_dict"]

    _, _, val_images, _ = split_train_validation()
    test_images, test_labels = load_mnist(train=False)
    test_inputs = test_images.flatten(1).numpy().astype(np.float64)
    labels = test_labels.numpy()

    float_model = build_model()
    float_model.load_state_dict(state_dict)
    float_model.eval()
    float_acc = accuracy(float_model, test_images, test_labels)

    layers = quantize_layers(state_dict)
    fill_act_scales(layers, val_images.flatten(1).numpy().astype(np.float64))
    int8_acc = accuracy_of(layers, test_inputs, labels)

    fixtures = load_stroke_fixtures()
    fixture_acc = fixture_accuracy(layers, fixtures)

    if float_acc < config.TARGET_FLOAT_ACC:
        raise SystemExit(f"float accuracy {float_acc:.2f}% is under the {config.TARGET_FLOAT_ACC}% target")
    if float_acc - int8_acc > config.TARGET_INT8_MAX_DROP:
        raise SystemExit(f"int8 accuracy {int8_acc:.2f}% is too far under float {float_acc:.2f}%")
    if len(fixtures) >= config.TARGET_FIXTURE_MIN_COUNT and fixture_acc < config.TARGET_FIXTURE_ACC:
        raise SystemExit(f"fixture accuracy {fixture_acc:.2f}% is under the {config.TARGET_FIXTURE_ACC}% target")

    version = model_version(layers)
    write_model_data(layers, version, {"float": float_acc, "int8": int8_acc, "fixture": fixture_acc})
    write_dev_fixtures(fixtures)
    write_goldens(layers, version, test_inputs, labels, fixtures)

    fixture_report = f"{fixture_acc:.2f}% on {len(fixtures)}" if fixtures else "no fixtures recorded yet"
    print(f"modelVersion {version}")
    print(f"float test accuracy {float_acc:.2f}%")
    print(f"int8 test accuracy {int8_acc:.2f}%")
    print(f"stroke fixture accuracy: {fixture_report}")


if __name__ == "__main__":
    main()
